"""MCP Mommy: local web dashboard + tray icon to start/stop/monitor the MCP
servers and the Discord bot in this project.

SECURITY: binds to 127.0.0.1 only and has no authentication. It gives control over
starting/stopping/restarting local subprocesses -- do not expose it on a network
interface, do not add port forwarding, and do not run it on a shared machine.
"""
import atexit
import os
import subprocess
import sys
import threading
import time
import webbrowser
from collections import deque

from flask import Flask, jsonify, render_template, send_file
from PIL import Image, ImageDraw
import pystray

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))

_venv_python = os.path.join(PROJECT_ROOT, ".venv", "Scripts", "python.exe")
PYTHON = _venv_python if os.path.exists(_venv_python) else sys.executable

SERVERS = {
    "ubc-mcp": os.path.join(PROJECT_ROOT, "mcp_server.py"),
    "google-tasks-mcp": os.path.join(PROJECT_ROOT, "google_tasks_mcp.py"),
    "gmail-mcp": os.path.join(PROJECT_ROOT, "gmail_mcp.py"),
    "rag-server": os.path.join(PROJECT_ROOT, "rag_server.py"),
    "discord-bot": os.path.join(PROJECT_ROOT, "discord_bot.py"),
    "screenshot-uploader": os.path.join(
        PROJECT_ROOT, "screenshot-app", "windows-uploader", "uploader.py"
    ),
}

LOG_LINES = 200

# Plain-text brief regenerated by the scheduled Claude task; rendered at the
# bottom of the dashboard. Missing file is fine -- the panel just says so.
BRIEF_PATH = os.path.join(PROJECT_ROOT, "src", "context", "ubc-brief.txt")
FAVICON_PATH = os.path.join(PROJECT_ROOT, "src", "assets", "profile.ico")

# Tracks the PID we last spawned for each managed server, on disk, so that if a
# previous MCP Mommy process dies uncleanly (crash, force-killed, etc. -- skipping
# stop()/atexit) we can find and clean up the orphan before starting a fresh one,
# instead of duplicate instances piling up (e.g. the Discord bot replying twice).
PIDS_DIR = os.path.join(PROJECT_ROOT, ".mcp_mommy_pids")
os.makedirs(PIDS_DIR, exist_ok=True)


class ManagedServer:
    def __init__(self, name, script_path):
        self.name = name
        self.script_path = script_path
        self.process = None
        self.logs = deque(maxlen=LOG_LINES)
        self.started_at = None
        self.pid_file = os.path.join(PIDS_DIR, f"{name}.pid")

    def _kill_tree(self, pid):
        # /T kills the whole process tree, not just this pid -- some launches on
        # this system leave a surviving child that plain terminate()/kill() miss.
        subprocess.run(
            ["taskkill", "/F", "/T", "/PID", str(pid)],
            capture_output=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )

    def _kill_stale_orphan(self):
        """If a previous MCP Mommy run left this exact child still alive (its own
        parent already exited), clean it up before starting a new one. Only ever
        acts on a PID we ourselves wrote to the pid file, and only after confirming
        that PID's command line still matches this script -- never touches anything
        else on the system (e.g. Claude Desktop's own independent instances)."""
        if not os.path.exists(self.pid_file):
            return
        try:
            with open(self.pid_file) as f:
                old_pid = int(f.read().strip())
            result = subprocess.run(
                ["powershell", "-NoProfile", "-Command",
                 f"(Get-CimInstance Win32_Process -Filter 'ProcessId={old_pid}').CommandLine"],
                capture_output=True, text=True, timeout=5,
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
            )
            if os.path.basename(self.script_path) in (result.stdout or ""):
                self._kill_tree(old_pid)
        except Exception:
            pass
        finally:
            try:
                os.remove(self.pid_file)
            except OSError:
                pass

    def start(self):
        if self.is_running():
            return
        self._kill_stale_orphan()
        self.process = subprocess.Popen(
            [PYTHON, self.script_path],
            cwd=PROJECT_ROOT,
            # stdio-transport MCP servers read from stdin; DEVNULL looks like an
            # immediately-closed client and makes them exit right away, so keep
            # stdin open (as a pipe we simply never write to) instead.
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
            # a console-subsystem child spawned from a windowless (pythonw) parent
            # would otherwise pop up its own blank terminal window on Windows
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        with open(self.pid_file, "w") as f:
            f.write(str(self.process.pid))
        self.started_at = time.time()
        threading.Thread(target=self._read_logs, daemon=True).start()

    def _read_logs(self):
        proc = self.process
        if not proc or not proc.stdout:
            return
        for line in proc.stdout:
            self.logs.append(line.rstrip())

    def stop(self):
        if self.process and self.process.poll() is None:
            self._kill_tree(self.process.pid)
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                pass
        self.process = None
        self.started_at = None
        try:
            os.remove(self.pid_file)
        except OSError:
            pass

    def is_running(self):
        return self.process is not None and self.process.poll() is None

    def status(self):
        return {
            "name": self.name,
            "running": self.is_running(),
            "pid": self.process.pid if self.is_running() else None,
            "uptime": int(time.time() - self.started_at) if self.is_running() and self.started_at else 0,
            "logs": list(self.logs)[-50:],
        }


managed = {name: ManagedServer(name, path) for name, path in SERVERS.items()}


@atexit.register
def _stop_all():
    for srv in managed.values():
        srv.stop()


app = Flask(__name__)

@app.route("/")
def index():
    return render_template("mcp_manager.html")


@app.route("/favicon.ico")
def favicon():
    if os.path.exists(FAVICON_PATH):
        return send_file(FAVICON_PATH, mimetype="image/vnd.microsoft.icon")
    return "", 404


@app.route("/api/brief")
def api_brief():
    try:
        with open(BRIEF_PATH, encoding="utf-8") as fh:
            text = fh.read()
        mins = int((time.time() - os.path.getmtime(BRIEF_PATH)) // 60)
        if mins < 1:
            age = "just now"
        elif mins < 90:
            age = f"{mins} min ago"
        else:
            age = f"{mins // 60}h ago"
        return jsonify({"exists": True, "text": text, "age": age})
    except OSError:
        return jsonify({
            "exists": False,
            "text": "(no brief yet -- the scheduled task writes this every 4 hours)",
            "age": "",
        })


@app.route("/api/status")
def api_status():
    return jsonify({name: srv.status() for name, srv in managed.items()})


@app.route("/api/<name>/start", methods=["POST"])
def api_start(name):
    if name not in managed:
        return jsonify({"error": "unknown server"}), 404
    managed[name].start()
    return jsonify(managed[name].status())


@app.route("/api/<name>/stop", methods=["POST"])
def api_stop(name):
    if name not in managed:
        return jsonify({"error": "unknown server"}), 404
    managed[name].stop()
    return jsonify(managed[name].status())


@app.route("/api/<name>/restart", methods=["POST"])
def api_restart(name):
    if name not in managed:
        return jsonify({"error": "unknown server"}), 404
    managed[name].stop()
    managed[name].start()
    return jsonify(managed[name].status())


@app.route("/api/quit", methods=["POST"])
def api_quit():
    # graceful shutdown -- stops every managed child (and cleans up their pid
    # files) before exiting, unlike force-killing this process from outside
    threading.Thread(target=lambda: (_stop_all(), os._exit(0)), daemon=True).start()
    return jsonify({"ok": True})


if __name__ == "__main__":
    for srv in managed.values():
        srv.start()
    port = int(os.getenv("MCP_MANAGER_PORT", "5055"))
    url = f"http://127.0.0.1:{port}"

    threading.Thread(
        target=lambda: app.run(host="127.0.0.1", port=port, debug=False, use_reloader=False),
        daemon=True,
    ).start()

    def _tray_icon_image():
        if os.path.exists(FAVICON_PATH):
            return Image.open(FAVICON_PATH)
        img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)
        draw.ellipse((2, 2, 61, 61), fill=(218, 119, 86, 255))
        draw.text((20, 18), "M", fill=(12, 12, 12, 255))
        return img

    def _on_open(icon, item):
        webbrowser.open(url)

    def _on_quit(icon, item):
        icon.stop()
        _stop_all()
        os._exit(0)

    tray = pystray.Icon(
        "mcp-mommy",
        icon=_tray_icon_image(),
        title="MCP Mommy",
        menu=pystray.Menu(
            pystray.MenuItem("Open Dashboard", _on_open, default=True),
            pystray.MenuItem("Quit", _on_quit),
        ),
    )
    tray.run()
